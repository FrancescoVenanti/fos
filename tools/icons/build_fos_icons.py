#!/usr/bin/env python3
"""Generate the FOs app icons from Lucide SVGs.

Rasterizes the Lucide icons named in MANIFEST (from the freeink-sdk lucide
submodule, ISC license) at several sizes into src/fos/ui/generated/AppIconData.h.
Strokes are thickened for the heavier FOs look. Output format: 1 bit per pixel,
rows MSB first and byte aligned, set bit = ink (fos::ui::Canvas::bits).

    .venv\\Scripts\\python -m pip install resvg-py pillow
    .venv\\Scripts\\python tools\\icons\\build_fos_icons.py
"""

import io
import os
import re
import sys

import resvg_py
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
LUCIDE = os.path.join(REPO, "freeink-sdk", "libs", "assets", "Icons", "lucide", "icons")
OUT = os.path.join(REPO, "src", "fos", "ui", "generated", "AppIconData.h")

SIZES = [36, 48, 64]
STROKE = "2.5"
THRESHOLD = 128

# C identifier -> Lucide icon name
MANIFEST = [
    ("budgeteer", "piggy-bank"),
    ("todo", "list-checks"),
    ("calendar", "calendar-days"),
    ("notes", "notebook-pen"),
    ("reader", "book-open"),
    ("readlater", "newspaper"),
    ("flashcards", "layers"),
    ("chess", "chess-knight"),
    ("puzzles", "puzzle"),
    ("timers", "timer"),
    ("calculator", "calculator"),
    ("wallet", "wallet"),
    ("habits", "flame"),
    ("terminal", "square-terminal"),
    ("lockscreen", "lock"),
    ("settings", "settings"),
]


def rasterize(svg_text, px):
    svg_text = re.sub(r'stroke-width="[0-9.]+"', 'stroke-width="%s"' % STROKE, svg_text)
    png = bytes(resvg_py.svg_to_bytes(svg_string=svg_text, width=px, height=px))
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    bg.paste(img, mask=img.split()[3])
    return bg.convert("L").resize((px, px))


def pack(img, px):
    pix = img.load()
    data = []
    for y in range(px):
        for xb in range(0, px, 8):
            byte = 0
            for b in range(8):
                x = xb + b
                if x < px and pix[x, y] < THRESHOLD:
                    byte |= 0x80 >> b
            data.append(byte)
    return data


def main():
    lines = [
        "// Generated by tools/icons/build_fos_icons.py from Lucide icons (ISC). Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace fos::ui::icons {",
        "",
    ]
    for size in SIZES:
        for alias, name in MANIFEST:
            with open(os.path.join(LUCIDE, name + ".svg"), encoding="utf-8") as f:
                svg = f.read()
            data = pack(rasterize(svg, size), size)
            lines.append("inline constexpr uint8_t %s_%d[%d] = {" % (alias, size, len(data)))
            for i in range(0, len(data), 16):
                lines.append("    " + ", ".join("0x%02X" % v for v in data[i:i + 16]) + ",")
            lines.append("};")
    lines.append("")
    lines.append("// Index order matches fos::AppId.")
    for size in SIZES:
        lines.append("inline constexpr const uint8_t* APP_%d[%d] = {" % (size, len(MANIFEST)))
        lines.append("    " + ", ".join("%s_%d" % (alias, size) for alias, _ in MANIFEST) + ",")
        lines.append("};")
    lines.append("")
    lines.append("}  // namespace fos::ui::icons")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("generated", os.path.relpath(OUT, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
