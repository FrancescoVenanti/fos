#!/usr/bin/env python3
"""Generate the FOs built-in UI fonts.

Converts the OFL fonts in tools/fonts/source/ with CrossPoint's
lib/EpdFont/scripts/fontconvert.py into src/fos/ui/fonts/*.h, plus
FosFontData.h (includes) and the font ids in FosFontIds.h.

Requires the font tool dependencies:
    python -m venv .venv
    .venv\\Scripts\\python -m pip install -r lib\\EpdFont\\scripts\\requirements.txt
    .venv\\Scripts\\python tools\\fonts\\build_fos_fonts.py
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, "source")
OUT = os.path.join(REPO, "src", "fos", "ui", "generated")
CONVERT = os.path.join(REPO, "lib", "EpdFont", "scripts", "fontconvert.py")

GROTESK_MEDIUM = os.path.join(SRC, "SpaceGrotesk-Medium.ttf")
GROTESK_BOLD = os.path.join(SRC, "SpaceGrotesk-Bold.ttf")
MONO_REGULAR = os.path.join(SRC, "SpaceMono-Regular.ttf")
MONO_BOLD = os.path.join(SRC, "SpaceMono-Bold.ttf")

LATIN = ["0x20,0x7E", "0xA0,0x17F", "0x2010,0x2027", "0x2030,0x203A", "0x20AC,0x20AC", "0x2190,0x2193",
         "0x2212,0x2212", "0x2713,0x2717"]
NUMERIC = ["0x20,0x20", "0x25,0x25", "0x2B,0x3A", "0x20AC,0x20AC", "0x2212,0x2212"]

# id name -> (point size, regular face, bold face or None, code point intervals or None for the default set)
FONTS = {
    "SMALL": (9, GROTESK_MEDIUM, GROTESK_BOLD, None),
    "BODY": (11, GROTESK_MEDIUM, GROTESK_BOLD, None),
    "TITLE": (15, GROTESK_BOLD, None, None),
    "DISPLAY": (26, GROTESK_BOLD, None, LATIN),
    "HUGE": (44, GROTESK_BOLD, None, NUMERIC),
    "MONO": (8, MONO_REGULAR, MONO_BOLD, None),
}

# Fixed, distinct, non-zero ids (font id 0 is the renderer's "not found").
FONT_IDS = {name: 0x0F050000 + i + 1 for i, name in enumerate(FONTS)}


def convert(symbol, size, face, intervals):
    # Repo-relative paths: the generated header records the command line.
    cmd = [sys.executable, os.path.relpath(CONVERT, REPO), symbol, str(size), os.path.relpath(face, REPO), "--2bit",
           "--compress"]
    for interval in intervals or []:
        cmd += ["--only-intervals", interval]
    out_path = os.path.join(OUT, symbol + ".h")
    env = dict(os.environ, PYTHONUTF8="1")
    with open(out_path, "w", encoding="utf-8", newline="\n") as out:
        subprocess.run(cmd, stdout=out, check=True, env=env, cwd=REPO)
    print("generated", os.path.relpath(out_path, REPO))


def main():
    os.makedirs(OUT, exist_ok=True)
    includes, ids = [], []
    for name, (size, regular, bold, intervals) in FONTS.items():
        base = "fos_%s" % name.lower()
        convert(base + "_regular", size, regular, intervals)
        includes.append('#include "%s_regular.h"' % base)
        if bold:
            convert(base + "_bold", size, bold, intervals)
            includes.append('#include "%s_bold.h"' % base)
        ids.append("#define FOS_%s_FONT_ID (%d)" % (name, FONT_IDS[name]))

    header = "// Generated by tools/fonts/build_fos_fonts.py. Do not edit.\n#pragma once\n\n"
    with open(os.path.join(OUT, "FosFontData.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n".join(includes) + "\n")
    with open(os.path.join(OUT, "FosFontIds.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n".join(ids) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
